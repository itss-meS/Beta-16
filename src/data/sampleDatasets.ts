export type PresetDatasetId = 'multi-account-full' | 'freelance-volatile' | 'short-incomplete';

export function buildPresetDataset(
  preset: PresetDatasetId,
  customRules: Record<string, TransactionCategory> = {}
): {
  transactions: Transaction[];
  report: IngestionReport;
} {
  const t0 = performance.now();

  if (preset === 'freelance-volatile') {
    const txns = parseCsvStatementText(
      IRREGULAR_FREELANCE_CSV,
      'Axis_Freelance_Checking_Jun_Oct.csv',
      customRules,
      'Axis Priority ••7740'
    );
    const { merged, report } = mergeAndDeduplicateTransactions(
      [],
      txns,
      ['Axis_Freelance_Checking_Jun_Oct.csv'],
      performance.now() - t0
    );
    return { transactions: merged, report };
  }

  if (preset === 'short-incomplete') {
    const txns = parseCsvStatementText(
      SHORT_INCOMPLETE_CSV,
      'HDFC_Partial_Sep_Oct.csv',
      customRules,
      'HDFC Savings ••4821'
    );
    const { merged, report } = mergeAndDeduplicateTransactions(
      [],
      txns,
      ['HDFC_Partial_Sep_Oct.csv'],
      performance.now() - t0
    );
    return { transactions: merged, report };
  }

  // Default: Multi-account CSV + overlapping CSV + PDF statement ingestion
  const icici = parseCsvStatementText(
    ICICI_SALARY_CSV,
    'ICICI_Salary_9104_Jun_Oct.csv',
    customRules,
    'ICICI Salary ••9104'
  );
  const hdfcMain = parseCsvStatementText(
    HDFC_SAVINGS_CSV,
    'HDFC_Savings_4821_Jun_Oct.csv',
    customRules,
    'HDFC Savings ••4821'
  );
  const hdfcOverlap = parseCsvStatementText(
    HDFC_OVERLAP_EXPORT_CSV,
    'HDFC_Savings_4821_Oct_Export2.csv',
    customRules,
    'HDFC Savings ••4821'
  );
  const sbiPdf = parsePdfStatementLines(
    SBI_CARD_PDF_LINES,
    'SBI_CreditCard_3319_Stmt.pdf',
    customRules,
    'SBI Credit Card ••3319'
  );

  // Merge sequentially so cross-file & self-transfer deduplication records every caught duplicate
  const step1 = mergeAndDeduplicateTransactions([], icici, ['ICICI_Salary_9104_Jun_Oct.csv'], 1);
  const step2 = mergeAndDeduplicateTransactions(
    step1.merged,
    hdfcMain,
    ['HDFC_Savings_4821_Jun_Oct.csv'],
    1
  );
  const step3 = mergeAndDeduplicateTransactions(
    step2.merged,
    hdfcOverlap,
    ['HDFC_Savings_4821_Oct_Export2.csv'],
    1
  );
  const step4 = mergeAndDeduplicateTransactions(
    step3.merged,
    sbiPdf,
    ['SBI_CreditCard_3319_Stmt.pdf'],
    performance.now() - t0
  );

  const combinedDedups = [
    ...step1.report.deduplicatedEntries,
    ...step2.report.deduplicatedEntries,
    ...step3.report.deduplicatedEntries,
    ...step4.report.deduplicatedEntries,
  ];

  const finalReport: IngestionReport = {
    id: `ing-preset-${Date.now()}`,
    timestamp: new Date().toISOString(),
    filesProcessed: [
      'ICICI_Salary_9104_Jun_Oct.csv',
      'HDFC_Savings_4821_Jun_Oct.csv',
      'HDFC_Savings_4821_Oct_Export2.csv',
      'SBI_CreditCard_3319_Stmt.pdf',
    ],
    totalRowsParsed: icici.length + hdfcMain.length + hdfcOverlap.length + sbiPdf.length,
    addedCount: step4.merged.length,
    deduplicatedCount: combinedDedups.length,
    deduplicatedEntries: combinedDedups,
    accountsUpdated: ['ICICI Salary ••9104', 'HDFC Savings ••4821', 'SBI Credit Card ••3319'],
    parseLatencyMs: Math.round((performance.now() - t0) * 10) / 10,
  };

  return { transactions: step4.merged, report: finalReport };
}
